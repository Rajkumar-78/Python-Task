import pandas as pd
import matplotlib.pyplot as plt
df = pd.read_csv("employees.csv")
avg_salary = df.groupby("department")["salary"].mean()
plt.figure(figsize=(8, 5))
bars = plt.bar(avg_salary.index, avg_salary.values)
plt.title("Average Salary per Department")
plt.xlabel("Department")
plt.ylabel("Average Salary")
plt.bar_label(bars, fmt="%.2f")
plt.tight_layout()
plt.savefig("bar_chart.png")
plt.close()
plt.figure(figsize=(8, 5))
plt.hist(df["salary"], bins=5, edgecolor="black")
plt.title("Salary Distribution")
plt.xlabel("Salary")
plt.ylabel("Frequency")
plt.tight_layout()
plt.savefig("histogram.png")
plt.close()
plt.figure(figsize=(8, 5))
for department in df["department"].unique():
    data = df[df["department"] == department]
    plt.scatter(data["id"], data["salary"], label=department)
plt.title("Employee ID vs Salary by Department")
plt.xlabel("Employee ID")
plt.ylabel("Salary")
plt.legend(title="Department")
plt.tight_layout()
plt.savefig("scatter_plot.png")
plt.close()
months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun"]
sales = [12, 15, 14, 18, 22, 25]
plt.figure(figsize=(8, 5))
plt.plot(months, sales, marker="o")
plt.title("Monthly Sales")
plt.xlabel("Month")
plt.ylabel("Sales")
plt.tight_layout()
plt.savefig("line_chart.png")
plt.close()
